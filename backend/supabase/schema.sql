create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- Shared helper
-- ---------------------------------------------------------------------------

create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- ---------------------------------------------------------------------------
-- Public perfume catalog
-- Mirrors perfume_cleaned_export.csv without fabricating unavailable fields.
-- ---------------------------------------------------------------------------

create table if not exists public.perfumes (
  id bigint generated by default as identity primary key,
  source_url text,
  name text not null,
  brand text not null,
  country text,
  gender text not null check (gender in ('women', 'men', 'unisex')),
  rating numeric(3, 2) not null default 0 check (rating >= 0 and rating <= 5),
  review_count integer not null default 0 check (review_count >= 0),
  release_year smallint check (release_year between 1700 and 2100),
  description text,
  image_url text,
  image_url_secondary text,
  perfumer_1 text,
  perfumer_2 text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.notes (
  id bigint generated by default as identity primary key,
  name text not null,
  normalized_name text generated always as (lower(trim(name))) stored,
  description text,
  created_at timestamptz not null default now(),
  unique (normalized_name)
);

create table if not exists public.perfume_notes (
  perfume_id bigint not null references public.perfumes(id) on delete cascade,
  note_id bigint not null references public.notes(id) on delete cascade,
  note_type text not null check (note_type in ('top', 'middle', 'base')),
  position smallint not null default 1 check (position >= 1),
  primary key (perfume_id, note_id, note_type)
);

create table if not exists public.accords (
  id bigint generated by default as identity primary key,
  name text not null,
  normalized_name text generated always as (lower(trim(name))) stored,
  created_at timestamptz not null default now(),
  unique (normalized_name)
);

create table if not exists public.perfume_accords (
  perfume_id bigint not null references public.perfumes(id) on delete cascade,
  accord_id bigint not null references public.accords(id) on delete cascade,
  position smallint not null default 1 check (position between 1 and 10),
  primary key (perfume_id, accord_id)
);

-- ---------------------------------------------------------------------------
-- User profile and personalization
-- auth.users remains the source of truth for credentials.
-- ---------------------------------------------------------------------------

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  display_name text,
  avatar_url text,
  bio text,
  is_public boolean not null default false,
  show_favorites boolean not null default true,
  show_reviews boolean not null default true,
  fragrance_dna jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.user_perfumes (
  user_id uuid not null references auth.users(id) on delete cascade,
  perfume_id bigint not null references public.perfumes(id) on delete cascade,
  collection_type text not null check (collection_type in ('favorite', 'wardrobe')),
  created_at timestamptz not null default now(),
  primary key (user_id, perfume_id, collection_type)
);

create table if not exists public.reviews (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  perfume_id bigint not null references public.perfumes(id) on delete cascade,
  rating smallint not null check (rating between 1 and 5),
  content text not null check (char_length(trim(content)) between 3 and 2000),
  sentiment text check (sentiment in ('positive', 'neutral', 'negative')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (user_id, perfume_id)
);

-- ---------------------------------------------------------------------------
