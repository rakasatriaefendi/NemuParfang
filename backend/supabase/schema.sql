drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
before update on public.profiles
for each row execute function public.set_updated_at();

drop trigger if exists reviews_set_updated_at on public.reviews;
create trigger reviews_set_updated_at
before update on public.reviews
for each row execute function public.set_updated_at();

-- Create a lightweight profile automatically after Supabase Auth signup.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute function public.handle_new_user();

-- ---------------------------------------------------------------------------
-- Row Level Security
-- Public catalog is readable by everyone. Writes require service-role access.
-- User-owned records are accessible only to their owner.
-- ---------------------------------------------------------------------------

alter table public.perfumes enable row level security;
alter table public.notes enable row level security;
alter table public.perfume_notes enable row level security;
alter table public.accords enable row level security;
alter table public.perfume_accords enable row level security;
alter table public.profiles enable row level security;
alter table public.user_perfumes enable row level security;
alter table public.reviews enable row level security;

drop policy if exists "Public can read perfumes" on public.perfumes;
create policy "Public can read perfumes"
on public.perfumes for select
using (true);

drop policy if exists "Public can read notes" on public.notes;
create policy "Public can read notes"
on public.notes for select
using (true);

drop policy if exists "Public can read perfume notes" on public.perfume_notes;
create policy "Public can read perfume notes"
on public.perfume_notes for select
using (true);

drop policy if exists "Public can read accords" on public.accords;
create policy "Public can read accords"
on public.accords for select
using (true);

drop policy if exists "Public can read perfume accords" on public.perfume_accords;
create policy "Public can read perfume accords"
on public.perfume_accords for select
using (true);

drop policy if exists "Users can read their own profile" on public.profiles;
create policy "Users can read their own profile"
on public.profiles for select
using (auth.uid() = id);

drop policy if exists "Public can read opted-in profiles" on public.profiles;
create policy "Public can read opted-in profiles"
on public.profiles for select
using (is_public = true);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
on public.profiles for update
using (auth.uid() = id)
with check (auth.uid() = id);

drop policy if exists "Users can read their own perfume collections" on public.user_perfumes;
create policy "Users can read their own perfume collections"
on public.user_perfumes for select
using (auth.uid() = user_id);

drop policy if exists "Public can read opted-in favorite collections" on public.user_perfumes;
create policy "Public can read opted-in favorite collections"
on public.user_perfumes for select
using (
  collection_type = 'favorite'
  and exists (
    select 1
    from public.profiles
    where profiles.id = user_perfumes.user_id
      and profiles.is_public = true
      and profiles.show_favorites = true
  )
);

drop policy if exists "Users can add their own perfume collections" on public.user_perfumes;
create policy "Users can add their own perfume collections"
on public.user_perfumes for insert
with check (auth.uid() = user_id);

drop policy if exists "Users can remove their own perfume collections" on public.user_perfumes;
create policy "Users can remove their own perfume collections"
on public.user_perfumes for delete
using (auth.uid() = user_id);

drop policy if exists "Public can read reviews" on public.reviews;
create policy "Public can read reviews"
on public.reviews for select
using (true);

drop policy if exists "Users can add their own reviews" on public.reviews;
create policy "Users can add their own reviews"
on public.reviews for insert
with check (auth.uid() = user_id);

drop policy if exists "Users can update their own reviews" on public.reviews;
create policy "Users can update their own reviews"
on public.reviews for update
using (auth.uid() = user_id)
with check (auth.uid() = user_id);

drop policy if exists "Users can remove their own reviews" on public.reviews;
create policy "Users can remove their own reviews"
on public.reviews for delete
using (auth.uid() = user_id);

